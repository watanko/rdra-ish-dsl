//! Python discriminated-union (`TypedDict`) emitters for entity lifecycle states.

use std::collections::BTreeSet;

use crate::{EmitError, Explored, OnDeadlock, Scope, StatesEmitter, View};
use rdra_ish_core::{
    collect_entity_state_variants, lifecycle::Caps, model::ColumnType, EntityStateVariant,
    EntityStateVariants, SemanticModel, StateFieldValue,
};

pub struct PythonStateUnionEmitter {
    pub caps: Caps,
}

impl Default for PythonStateUnionEmitter {
    fn default() -> Self {
        Self { caps: Caps::STATES }
    }
}

impl StatesEmitter for PythonStateUnionEmitter {
    fn on_deadlock(&self) -> OnDeadlock {
        OnDeadlock::Refuse
    }

    fn emit(
        &self,
        model: &SemanticModel,
        view: &View,
        _explored: &Explored,
    ) -> Result<String, EmitError> {
        let buc_filter = match &view.scope {
            Scope::Bucs(ids) => ids.clone(),
            Scope::Whole | Scope::UseCases(_) => vec![],
        };
        let collections = collect_entity_state_variants(model, &buc_filter, self.caps);
        Ok(emit_python_state_unions(model, &collections))
    }
}

/// The `TypedDict` state unions of `collections`. `model` gives each column its declared
/// type: a state axis is abstract (an Int is one of the bounded values, a nullable column
/// is `present`), and the union types it by the column, not by the abstract value.
pub fn emit_python_state_unions(
    model: &SemanticModel,
    collections: &[EntityStateVariants],
) -> String {
    let mut body = String::new();
    for collection in collections {
        if collection.variants.is_empty() {
            continue;
        }
        body.push_str(&emit_entity_union(model, collection));
        body.push('\n');
    }

    let mut out = String::from(
        "# Generated by rdra-ish. Do not edit manually.\nfrom __future__ import annotations\n\n",
    );
    if body.contains("datetime.") {
        out.push_str("import datetime\n");
    }
    out.push_str("import typing as _t\n\n");
    if !body.is_empty() {
        out.push('\n');
        out.push_str(&body);
    }
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

fn emit_entity_union(model: &SemanticModel, collection: &EntityStateVariants) -> String {
    let type_name = to_pascal_case(&collection.entity_id);
    let mut out = String::new();

    // Patterns that differ only in a value the column type does not tell apart (two Int
    // values) print the same shape; keep one copy.
    let mut unique_shapes: Vec<(String, Vec<(String, String)>)> = Vec::new();
    for variant in &collection.variants {
        let fields = variant_fields(model, collection, variant);
        if !unique_shapes.iter().any(|(_, f)| *f == fields) {
            unique_shapes.push((variant.discriminator.clone(), fields));
        }
    }

    let mut used_names: BTreeSet<String> = BTreeSet::new();
    let mut variant_names: Vec<String> = Vec::new();
    for (disc, fields) in &unique_shapes {
        let base = format!("{type_name}{}", to_pascal_case(disc));
        let mut class_name = base.clone();
        let mut n = 2;
        while !used_names.insert(class_name.clone()) {
            class_name = format!("{base}{n}");
            n += 1;
        }
        out.push_str(&emit_typed_dict(&class_name, fields));
        out.push_str("\n\n");
        variant_names.push(class_name);
    }

    out.push_str(&format!(
        "# Reachable state variants for {}.\n",
        collection.entity_id
    ));
    out.push_str(&format!(
        "{type_name}: _t.TypeAlias = {}\n",
        variant_names.join(" | ")
    ));
    out
}

fn variant_fields(
    model: &SemanticModel,
    collection: &EntityStateVariants,
    variant: &EntityStateVariant,
) -> Vec<(String, String)> {
    let mut fields = vec![(
        collection.discriminator_column.clone(),
        format!("_t.Literal[{}]", py_string_literal(&variant.discriminator)),
    )];

    for (column, value) in &variant.fields {
        let declared = model
            .entities
            .get(collection.entity)
            .and_then(|e| e.columns.iter().find(|c| c.name == *column))
            .map(|c| &c.col_type);
        fields.push((column.clone(), py_type_for_field(model, value, declared)));
    }
    fields
}

fn emit_typed_dict(class_name: &str, fields: &[(String, String)]) -> String {
    let all_plain = fields.iter().all(|(name, _)| is_plain_py_ident(name));
    if all_plain {
        let mut out = format!("class {class_name}(_t.TypedDict):\n");
        for (name, ty) in fields {
            out.push_str(&format!("    {name}: {ty}\n"));
        }
        out
    } else {
        let mut out = format!("{class_name} = _t.TypedDict(\n    \"{class_name}\",\n    {{\n");
        for (name, ty) in fields {
            out.push_str(&format!("        {}: {ty},\n", py_string_literal(name)));
        }
        out.push_str("    },\n)\n");
        out
    }
}

fn is_plain_py_ident(name: &str) -> bool {
    const KEYWORDS: [&str; 35] = [
        "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class",
        "continue", "def", "del", "elif", "else", "except", "finally", "for", "from", "global",
        "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return",
        "try", "while", "with", "yield",
    ];
    let mut chars = name.chars();
    let valid_chars = chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_');
    valid_chars && !KEYWORDS.contains(&name) && name != "self"
}

fn py_type_for_field(
    model: &SemanticModel,
    value: &StateFieldValue,
    declared: Option<&ColumnType>,
) -> String {
    match value {
        StateFieldValue::Enum(variant) => {
            format!("_t.Literal[{}]", py_string_literal(variant))
        }
        StateFieldValue::Bool(_) => "bool".to_string(),
        StateFieldValue::Null => "None".to_string(),
        // The value is one of the bounded domain `0..=int_max`, not a fact of the row.
        StateFieldValue::Int(_) => "int".to_string(),
        StateFieldValue::Present { pg_type } => match pg_type.as_deref() {
            Some("timestamptz" | "timestamp") => "datetime.datetime".to_string(),
            Some("date") => "datetime.date".to_string(),
            Some("uuid") => "str".to_string(),
            Some("json" | "jsonb") => "dict[str, _t.Any]".to_string(),
            Some("money" | "decimal") => "float".to_string(),
            Some(_) => "str".to_string(),
            None => declared.map_or_else(|| "_t.Any".to_string(), |t| py_column_type(model, t)),
        },
    }
}

fn py_column_type(model: &SemanticModel, col_type: &ColumnType) -> String {
    match col_type {
        ColumnType::Int => "int".to_string(),
        ColumnType::Money | ColumnType::Decimal => "float".to_string(),
        ColumnType::String => "str".to_string(),
        ColumnType::DateTime => "datetime.datetime".to_string(),
        ColumnType::Date => "datetime.date".to_string(),
        ColumnType::Bool => "bool".to_string(),
        ColumnType::Enum(values) => literal_union(values),
        ColumnType::Variation(key) => model
            .variations
            .get(*key)
            .map_or_else(|| "str".to_string(), |v| literal_union(&v.values)),
    }
}

fn literal_union(values: &[String]) -> String {
    if values.is_empty() {
        return "_t.NoReturn".to_string();
    }
    let items: Vec<String> = values.iter().map(|v| py_string_literal(v)).collect();
    format!("_t.Literal[{}]", items.join(", "))
}

fn py_string_literal(value: &str) -> String {
    format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('\n', "\\n")
    )
}

fn to_pascal_case(id: &str) -> String {
    let mut out = String::new();
    let mut upper = true;
    for ch in id.chars() {
        if !ch.is_ascii_alphanumeric() {
            upper = true;
            continue;
        }
        if upper {
            out.extend(ch.to_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    match out.chars().next() {
        Some(c) if c.is_ascii_alphabetic() => out,
        _ => format!("V{out}"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use rdra_ish_core::analysis::build_model;
    use rdra_ish_syntax::parse;

    fn model_from(src: &str) -> SemanticModel {
        let (ast, parse_errors) = parse(src);
        assert!(parse_errors.is_empty(), "parse errors: {parse_errors:?}");
        let (model, diags) = build_model(&ast);
        assert!(diags.is_empty(), "unexpected diagnostics: {diags:?}");
        model
    }

    const ORDER_SRC: &str = r#"
entity Order "注文" {
  id:           Int @pk
  status:       Enum(pending, paid, shipped, delivered, cancelled) @default(pending)
  delivered_at: DateTime @null
}
usecase PlaceOrder  "注文確定"
usecase CapturePay  "決済確定"
usecase ShipOrder   "発送"
usecase DeliverOrder "配達確認"
usecase CancelOrder "注文キャンセル"
creates(PlaceOrder, Order)
updates(CapturePay,   Order)
updates(ShipOrder,    Order)
updates(DeliverOrder, Order)
updates(CancelOrder,  Order)
transitions(CapturePay, Order.status, pending -> paid)
transitions(ShipOrder, Order.status, paid -> shipped)
transitions(DeliverOrder, Order.status, shipped -> delivered)
transitions(CancelOrder, Order.status, pending -> cancelled)
sets(usecase::DeliverOrder, Order.delivered_at == present)
"#;

    #[test]
    fn python_state_union_contains_expected_variants() {
        let model = model_from(ORDER_SRC);
        let collections = collect_entity_state_variants(&model, &[], Caps::STATES);
        let out = emit_python_state_unions(&model, &collections);
        assert!(out.contains("import datetime"), "{out}");
        assert!(out.contains("class OrderPending(_t.TypedDict):"), "{out}");
        assert!(out.contains("status: _t.Literal[\"pending\"]"), "{out}");
        assert!(out.contains("delivered_at: None"), "{out}");
        assert!(out.contains("delivered_at: datetime.datetime"), "{out}");
        assert!(out.contains("Order: _t.TypeAlias = "), "{out}");
    }

    #[test]
    fn int_axis_is_int_and_patterns_merge() {
        let model = model_from(
            r#"
entity Item "商品" {
  id: Int @pk
  status: Enum(active, archived) @default(active)
  stock: Int @default("1")
}
usecase Register "登録"
usecase Restock "入荷"
usecase Archive "廃止"
creates(Register, Item)
updates(Restock, Item)
sets(Restock, Item.stock == 3)
transitions(Archive, Item.status, active -> archived)
forbidden(Item, stock > 4)
"#,
        );
        let collections = collect_entity_state_variants(&model, &[], Caps::STATES);
        let out = emit_python_state_unions(&model, &collections);
        assert!(out.contains("stock: int"), "{out}");
        assert!(!out.contains("stock: 1") && !out.contains("stock: 3"), "{out}");
        assert_eq!(out.matches("status: _t.Literal[\"active\"]").count(), 1, "{out}");
    }

    #[test]
    fn emitter_matches_helper() {
        let model = model_from(ORDER_SRC);
        let view = View::whole();
        let from_emitter = PythonStateUnionEmitter::default()
            .emit(&model, &view, &Explored::default())
            .unwrap();
        let collections = collect_entity_state_variants(&model, &[], Caps::STATES);
        assert_eq!(
            from_emitter,
            emit_python_state_unions(&model, &collections)
        );
    }
}
